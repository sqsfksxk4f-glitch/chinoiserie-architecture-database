"""
One-time script: translate all keywords + country names to every official language
using the Yunwu AI API, and save as a Python dict.
"""
import json
import re
import sys
import os
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import openai
import config
from ui.keyword_gen import COUNTRY_GROUPS, CORE_KEYWORDS

YUNWU_BASE_URL, DEFAULT_MODEL, API_KEY = config.get_llm("keyword_translate")

# All Chinese keywords to translate
KEYWORDS_ZH = CORE_KEYWORDS["zh"]

# English keywords (for reference, not translated)
KEYWORDS_EN = CORE_KEYWORDS["en"]

# Collect all unique languages from COUNTRY_GROUPS
unique_langs = set()
for _region, countries in COUNTRY_GROUPS:
    for c in countries:
        for lang in c[2].split(","):
            lang = lang.strip()
            if lang not in ("中文", "English"):
                unique_langs.add(lang)

unique_langs = sorted(unique_langs)
print(f"Unique languages to translate: {len(unique_langs)}")
print(f"Languages: {unique_langs}")

# Collect all Chinese country names
all_country_names = []
for _region, countries in COUNTRY_GROUPS:
    for c in countries:
        all_country_names.append(c[0])

all_texts = KEYWORDS_ZH + all_country_names
print(f"Keywords: {len(KEYWORDS_ZH)}, Countries: {len(all_country_names)}")
print(f"Total texts to translate per language: {len(all_texts)}")

client = openai.OpenAI(base_url=YUNWU_BASE_URL, api_key=API_KEY)

translations = {}
failed = []

for i, lang in enumerate(unique_langs):
    print(f"\n[{i+1}/{len(unique_langs)}] Translating to {lang}...", flush=True)

    prompt = f"""Translate the following Chinese phrases to {lang}.
Return a JSON object mapping each original Chinese phrase to its translation.

Phrases to translate:
{json.dumps(all_texts, ensure_ascii=False)}

Return ONLY the JSON object, nothing else. Example:
{{"中式建筑": "translated text", "日本": "translated text"}}"""

    try:
        response = client.chat.completions.create(
            model=DEFAULT_MODEL,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.3,
            max_tokens=4000,
            timeout=60,
        )
        content = response.choices[0].message.content.strip()
        json_match = re.search(r'\{[\s\S]*\}', content)
        if json_match:
            result = json.loads(json_match.group(0))
            translations[lang] = {}
            for original, translated in result.items():
                if isinstance(translated, str) and translated.strip():
                    translations[lang][original.strip()] = translated.strip()
            print(f"  Got {len(translations[lang])} translations", flush=True)
        else:
            print(f"  No JSON found in response", flush=True)
            failed.append(lang)
    except Exception as e:
        print(f"  Error: {e}", flush=True)
        failed.append(lang)

    time.sleep(0.3)

# Save translations
output_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "keyword_translations.py")
with open(output_path, "w", encoding="utf-8") as f:
    f.write("# Auto-generated keyword translations for all official languages\n")
    f.write(f"# Generated by build_translations.py\n")
    f.write(f"# Keywords: {len(KEYWORDS_ZH)}, Languages: {len(translations)}\n\n")
    f.write("KEYWORD_TRANSLATIONS = ")
    json_str = json.dumps(translations, ensure_ascii=False, indent=2)
    f.write(json_str)
    f.write("\n")

print(f"\nSaved to {output_path}")
print(f"Successful: {len(translations)} languages")
if failed:
    print(f"Failed: {failed}")
